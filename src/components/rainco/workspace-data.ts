function buildScorecardEntries(
  selections: Array<{
    mainId: string;
    mainCode: string;
    mainName: string;
    criteriaType: CriteriaType;
    subId: string;
    subCode: string;
    subIndication: string;
    criteriaValue: string;
    condition: string;
    marks: number;
  }>,
): EvaluationSubCriteriaEntry[] {
  return selections.map((s) => ({
    ...s,
    score: 10,
  }));
}

